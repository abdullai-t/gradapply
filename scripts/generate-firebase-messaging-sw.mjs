#!/usr/bin/env node
/**
 * Writes public/firebase-messaging-sw.js with Firebase web config from env.
 * Service workers cannot read Next.js env at runtime.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outPath = path.join(root, "public", "firebase-messaging-sw.js");

function loadEnvFile(filePath) {
  if (!existsSync(filePath)) return;
  const text = readFileSync(filePath, "utf8");
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    if (process.env[key] !== undefined) continue;
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    process.env[key] = value;
  }
}

loadEnvFile(path.join(root, ".env"));
loadEnvFile(path.join(root, ".env.local"));

const config = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY?.trim() ?? "",
  authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN?.trim() ?? "",
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID?.trim() ?? "",
  appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID?.trim() ?? "",
  messagingSenderId:
    process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID?.trim() ?? "",
};

if (!config.apiKey || !config.projectId) {
  console.warn(
    "WARN: NEXT_PUBLIC_FIREBASE_* vars missing — firebase-messaging-sw.js will not initialize until you set .env and re-run generate:fcm-sw",
  );
} else {
  console.log(`FCM service worker config: project ${config.projectId}`);
}

const template = `/* Generated by scripts/generate-firebase-messaging-sw.mjs — do not edit manually. */
importScripts(
  "https://www.gstatic.com/firebasejs/12.14.0/firebase-app-compat.js",
);
importScripts(
  "https://www.gstatic.com/firebasejs/12.14.0/firebase-messaging-compat.js",
);

const firebaseConfig = ${JSON.stringify(config, null, 2)};

if (firebaseConfig.apiKey && firebaseConfig.projectId) {
  firebase.initializeApp(firebaseConfig);
  const messaging = firebase.messaging();

  messaging.onBackgroundMessage(function (payload) {
    const title =
      payload.notification?.title ||
      payload.data?.title ||
      "GradApply reminder";
    const body =
      payload.notification?.body ||
      payload.data?.body ||
      "You have an application update.";
    const url = payload.data?.url || payload.fcmOptions?.link || "/schools";
    const options = {
      body: body,
      data: { url: url, schoolId: payload.data?.schoolId || "" },
      tag: payload.data?.tag || "gradapply-deadline",
    };
    self.registration.showNotification(title, options);
  });

  self.addEventListener("notificationclick", function (event) {
    event.notification.close();
    const target = event.notification.data?.url || "/schools";
    event.waitUntil(
      clients
        .matchAll({ type: "window", includeUncontrolled: true })
        .then(function (clientList) {
          for (const client of clientList) {
            if ("focus" in client) {
              client.navigate(target);
              return client.focus();
            }
          }
          if (clients.openWindow) {
            return clients.openWindow(target);
          }
        }),
    );
  });
}
`;

writeFileSync(outPath, template);
console.log(`Wrote ${path.relative(root, outPath)}`);
